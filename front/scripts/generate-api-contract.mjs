// @ts-check
import { execSync } from "node:child_process";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Génère les artefacts TypeScript du contrat OpenAPI :
 * 1. shared/api/schema.d.ts : types OpenAPI bruts.
 * 2. shared/api/enums.ts : valeurs runtime des enums.
 * 3. shared/api/contract.ts : alias lisibles BackendXxx.
 *
 * Verrouille automatiquement les fichiers générés en lecture seule (0o444)
 * pour qu'IntelliJ, WebStorm et VSCode affichent le cadenas 🔒 et bloquent l'édition.
 */
const here = dirname(fileURLToPath(import.meta.url));
const SPEC = resolve(here, "../../api/openapi.json");
const OUT_SCHEMA = resolve(here, "../shared/api/schema.d.ts");
const OUT_ENUMS = resolve(here, "../shared/api/enums.ts");
const OUT_CONTRACT = resolve(here, "../shared/api/contract.ts");

const ALL_GENERATED = [OUT_SCHEMA, OUT_ENUMS, OUT_CONTRACT];

// 0. Si le fichier SPEC n'est pas accessible (ex. build Docker autonome où le contexte est restreint à front/),
// conserver les fichiers générés existants s'ils sont déjà présents.
if (!existsSync(SPEC)) {
  if (ALL_GENERATED.every((file) => existsSync(file))) {
    console.log(
      `ℹ️ Spécification OpenAPI introuvable (${SPEC}), conservation des types générés existants.`
    );
    process.exit(0);
  }
  throw new Error(`Fichier de spécification OpenAPI introuvable : ${SPEC}`);
}

// Déverrouiller les fichiers existants s'ils étaient en lecture seule
for (const file of ALL_GENERATED) {
  if (existsSync(file)) {
    try {
      chmodSync(file, 0o666);
    } catch {
      // Ignorer si déjà accessible
    }
  }
}

// 1. Génération des types bruts via openapi-typescript
console.log("🚀 Génération OpenAPI ➔ schema.d.ts...");
execSync(`npx openapi-typescript "${SPEC}" -o "${OUT_SCHEMA}"`, {
  cwd: resolve(here, ".."),
  stdio: "inherit",
});

const spec = JSON.parse(readFileSync(SPEC, "utf8"));
const schemas = spec.components?.schemas ?? {};

// En-tête standard reconnu par les IDEs
const GENERATED_HEADER = `/**
 * @generated
 * Code generated by \`npm run generate:api\` from api/openapi.json — DO NOT EDIT DIRECTLY.
 *
 * Ce fichier est généré automatiquement. Toute modification manuelle sera écrasée.
 * @readonly
 */
`;

// 2. Enums runtime (enums.ts)
const enums = Object.entries(schemas)
  .filter(([, s]) => Array.isArray(s.enum))
  .sort(([a], [b]) => a.localeCompare(b));

if (enums.length === 0) {
  throw new Error(`Aucune enum trouvée dans ${SPEC} — le contrat est-il à jour ?`);
}

const enumDeclarations = enums
  .map(
    ([name, s]) =>
      `export const ${name} = [${s.enum.map((v) => JSON.stringify(v)).join(", ")}] as const;\nexport type ${name} = (typeof ${name})[number];`
  )
  .join("\n\n");

const enumContent = `${GENERATED_HEADER}
// Le pendant runtime de \`schema.d.ts\` : les mêmes enums sous forme de valeurs utilisables à
// l'exécution (options de formulaire, \`z.enum\`). Les types sont dans \`contract.ts\`.

${enumDeclarations}
`;

writeFileSync(OUT_ENUMS, enumContent, "utf8");
console.log(`✨ ${enums.length} enums → shared/api/enums.ts`);

// 3. Types aliases (contract.ts)
const schemaNames = Object.keys(schemas).sort((a, b) => a.localeCompare(b));

if (schemaNames.length === 0) {
  throw new Error(`Aucun schéma trouvé dans ${SPEC} — le contrat est-il à jour ?`);
}

const typeAliases = schemaNames
  .map((name) => `export type Backend${name} = Schemas["${name}"];`)
  .join("\n");

const contractContent = `${GENERATED_HEADER}
// Alias lisibles sur les schémas générés (\`components["schemas"]["X"]\` est exact mais verbeux).

import type { components } from "./schema";

type Schemas = components["schemas"];

${typeAliases}
`;

writeFileSync(OUT_CONTRACT, contractContent, "utf8");
console.log(`✨ ${schemaNames.length} types → shared/api/contract.ts`);

// 4. Post-traitement de schema.d.ts (injection de l'en-tête @generated)
if (existsSync(OUT_SCHEMA)) {
  const schemaRaw = readFileSync(OUT_SCHEMA, "utf8");
  if (!schemaRaw.includes("@generated")) {
    writeFileSync(OUT_SCHEMA, `${GENERATED_HEADER}\n${schemaRaw}`, "utf8");
    console.log(`✨ En-tête @generated injecté → shared/api/schema.d.ts`);
  }
}

// 5. Verrouiller les fichiers en lecture seule (0o444) pour les IDEs
for (const file of ALL_GENERATED) {
  if (existsSync(file)) {
    try {
      chmodSync(file, 0o444);
    } catch {
      // Ignorer sur les environnements qui ne supportent pas le verrouillage
    }
  }
}
console.log("🔒 Fichiers marqués en lecture seule pour l'IDE (IntelliJ / WebStorm / VSCode).");


